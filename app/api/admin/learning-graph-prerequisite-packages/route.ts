import { NextRequest, NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server-create-client'
import { createServerClient } from '@supabase/ssr'
import { cookies } from 'next/headers'

const adminDb = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!)

async function requireAdmin() {
  const cookieStore = await cookies()
   const sb = createServerClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    { cookies: { get: (name) => cookieStore.get(name)?.value } })
  const { data: { user } } = await sb.auth.getUser()
  if (!user) return null
  const { data } = await adminDb.from('profiles').select('is_admin').eq('id', user.id).maybeSingle()
  return data?.is_admin === true ? user : null
}

export async function GET() {
  if (!await requireAdmin()) return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
  const [packages, items, nodes, versions] = await Promise.all([
    adminDb.from('learning_graph_prerequisite_packages').select('*').order('updated_at', { ascending: false }).limit(100),
    adminDb.from('learning_graph_prerequisite_items').select('*').order('created_at', { ascending: true }).limit(500),
    adminDb.from('learning_graph_nodes').select('id,label,node_type,subject,grade').eq('is_active', true)
      .in('node_type', ['topic', 'learning_objective']).order('label'),
    adminDb.from('curriculum_versions').select('id,code,title,status').order('academic_year_start', { ascending: false }),
  ])
  const error = packages.error || items.error || nodes.error || versions.error
  if (error) return NextResponse.json({ error: error.message }, { status: 500 })
  return NextResponse.json({ packages: packages.data || [], items: items.data || [], nodes: nodes.data || [], versions: versions.data || [] })
}

export async function POST(req: NextRequest) {
  const user = await requireAdmin()
  if (!user) return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
  const body = await req.json()
  let result
  if (body.action === 'create') {
    result = await adminDb.rpc('create_learning_graph_prerequisite_package_v1', {
      p_name: body.name, p_subject: body.subject, p_grade: body.grade,
      p_curriculum_version_id: body.curriculumVersionId,
      p_source_reference: body.sourceReference, p_created_by: user.id,
      p_items: [{ source_node_id: body.sourceNodeId, target_node_id: body.targetNodeId,
        confidence: Number(body.confidence), rationale: body.rationale }],
    })
  } else if (body.action === 'review') {
    result = await adminDb.rpc('review_learning_graph_prerequisite_item_v1', {
      p_item_id: body.itemId, p_decision: body.decision,
      p_reviewer_id: user.id, p_review_note: body.reviewNote || null,
    })
  } else if (body.action === 'publish') {
    result = await adminDb.rpc('publish_learning_graph_prerequisite_package_v1', {
      p_package_id: body.packageId, p_publisher_id: user.id,
    })
  } else {
    return NextResponse.json({ error: 'Geçersiz işlem' }, { status: 400 })
  }
  if (result.error) return NextResponse.json({ error: result.error.message }, { status: 400 })
  return NextResponse.json({ ok: true, result: result.data })
}
